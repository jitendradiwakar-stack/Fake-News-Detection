def seed_database():
    print("SatyaCheck: Starting comprehensive fact-check seeder...")
    inserted = 0
    updated = 0
    
    for seed in FACT_CHECK_SEEDS:
        try:
            is_new = db_manager.upsert_fact_check(seed)
            if is_new:
                inserted += 1
            else:
                updated += 1
        except Exception as e:
            print(f"  Error inserting seed {seed['external_id']}: {e}")
            
    total = db_manager.get_fact_checks_count()
    print(f"Seeding completed successfully! Inserted: {inserted}, Updated: {updated}. Total claims now: {total}")
    return total

